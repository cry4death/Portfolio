export const courseCount = courseGroups.reduce((sum, group) => sum + group.courses.length, 0);
export function formatCourseCount(count: number) {
  const lastTwo = count % 100;
  const last = count % 10;
  const word = lastTwo >= 11 && lastTwo <= 14 ? 'дисциплин' : last === 1 ? 'дисциплина' : last >= 2 && last <= 4 ? 'дисциплины' : 'дисциплин';
  return `${count} ${word}`;
}
